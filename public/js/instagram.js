let _igData = null;

async function loadIgData() {
  if (_igData) return _igData;
  try {
    const r = await fetch('./instagram-data.json');
    if (r.ok) {
      const d = await r.json();
      if (Array.isArray(d.works) && d.works.length > 0) {
        _igData = d.works;
        return _igData;
      }
    }
  } catch (_) {}
  _igData = STATIC_WORKS;
  return _igData;
}

let _activeCat = 'all';

function renderAiGrid(works) {
  const grid = document.getElementById('ai-grid');
  if (!grid) return;
  const filtered = _activeCat === 'all' ? works : works.filter(w => w.cat === _activeCat);
  grid.innerHTML = '';
  if (filtered.length === 0) {
    grid.innerHTML = '<div class="ai-empty">Nessun lavoro in questa categoria.</div>';
    return;
  }
  filtered.forEach(w => {
    const card = document.createElement('div');
    card.className = 'ai-card';
    card.style.setProperty('--ai-accent', w.accent);
    const hasImg = w.image_url && !w.image_url.startsWith('placeholder');
    card.innerHTML =
      `<a class="ai-card-img" href="${w.ig_url || '#'}" target="_blank" rel="noopener" style="background:${w.color};" aria-label="${w.title} — apri su Instagram">` +
        (hasImg
          ? `<img src="${w.image_url}" alt="${w.title}" loading="lazy">`
          : (w.svg || '')) +
        `<div class="ai-card-overlay"><span class="ai-card-open">↗</span></div>` +
      `</a>` +
      `<div class="ai-card-body">` +
        `<div class="ai-card-cat">${w.cat}</div>` +
        `<div class="ai-card-title">${w.title}</div>` +
        `<div class="ai-card-caption">${w.caption}</div>` +
        `<div class="ai-card-tool">${w.tool}</div>` +
      `</div>`;
    grid.appendChild(card);
  });
}

export async function initAiSection() {
  const works = await loadIgData();

  document.querySelectorAll('.ai-fb').forEach(btn => {
    btn.addEventListener('click', () => {
      document.querySelectorAll('.ai-fb').forEach(b => b.classList.remove('on'));
      btn.classList.add('on');
      _activeCat = btn.dataset.cat;
      renderAiGrid(works);
    });
  });

  renderAiGrid(works);
}
